local paths = require "passaporta.paths"

describe("paths.normalize_local", function()
  local root = "/home/u/proj"
  it("maps files and directories under the root", function()
    assert.are.equal("src/a.lua", paths.normalize_local("/home/u/proj/src/a.lua", root))
    assert.are.equal("doc/", paths.normalize_local("/home/u/proj/doc/", root))
  end)
  it("maps the root itself to the empty string", function()
    assert.are.equal("", paths.normalize_local("/home/u/proj", root))
    assert.are.equal("", paths.normalize_local("/home/u/proj/", root))
    assert.are.equal("", paths.normalize_local("/home/u/proj", root .. "/"))
  end)
  it("returns nil for paths outside the root", function()
    assert.is_nil(paths.normalize_local("/etc/hosts", "/home/u/proj"))
  end)
  it("does not treat a sibling with a shared prefix as inside", function()
    assert.is_nil(paths.normalize_local("/home/u/project2/x", "/home/u/project"))
    assert.is_nil(paths.normalize_local("/home/u/proj-backup/x", root))
  end)
  it("does not expand environment variables in file names", function()
    assert.are.equal("$HOME.txt", paths.normalize_local("/proj/$HOME.txt", "/proj"))
    assert.are.equal("a.txt", paths.normalize_local("/$HOME/a.txt", "/$HOME"))
  end)
end)

describe("paths.path_matches", function()
  it("matches component-wise", function()
    assert.is_true(paths.path_matches("src/a/b", "src"))
    assert.is_true(paths.path_matches("src", "src"))
    assert.is_true(paths.path_matches("src/", "src"))
    assert.is_true(paths.path_matches("src/a", "src/"))
    assert.is_false(paths.path_matches("srcs/a", "src"))
    assert.is_false(paths.path_matches("a/src", "src"))
  end)
  it("matches everything with an empty prefix", function()
    assert.is_true(paths.path_matches("", ""))
    assert.is_true(paths.path_matches("a/b", ""))
  end)
end)

describe("paths.normalize_mapping_local", function()
  it("normalizes root spellings to the empty string", function()
    assert.are.equal("", paths.normalize_mapping_local(nil))
    assert.are.equal("", paths.normalize_mapping_local "")
    assert.are.equal("", paths.normalize_mapping_local ".")
    assert.are.equal("", paths.normalize_mapping_local "/")
    assert.are.equal("", paths.normalize_mapping_local "./")
  end)
  it("strips ./ and leading/trailing slashes", function()
    assert.are.equal("src/x", paths.normalize_mapping_local "./src/x/")
    assert.are.equal("src", paths.normalize_mapping_local "/src")
    assert.are.equal("src/x", paths.normalize_mapping_local "src/x")
  end)
end)

describe("paths.join_remote", function()
  it("joins under a root mapping", function()
    local m = { ["local"] = "", remote = "/var/www/app" }
    assert.are.equal("/var/www/app/src/a.js", paths.join_remote(m, "src/a.js"))
  end)
  it("joins under a sub mapping", function()
    local m = { ["local"] = "example.com", remote = "/var/www/example.com" }
    assert.are.equal("/var/www/example.com", paths.join_remote(m, "example.com"))
    assert.are.equal("/var/www/example.com/index.js", paths.join_remote(m, "example.com/index.js"))
    assert.are.equal("/var/www/example.com/sub/", paths.join_remote(m, "example.com/sub/"))
  end)
  it("keeps relative remote paths relative", function()
    assert.are.equal(
      "www/wp-config.php",
      paths.join_remote({ ["local"] = "wp-config.php", remote = "www/wp-config.php" }, "wp-config.php")
    )
    assert.are.equal(
      "www/themes/x/style.css",
      paths.join_remote({ ["local"] = "src/themes/x", remote = "www/themes/x" }, "src/themes/x/style.css")
    )
    assert.are.equal("www/a.txt", paths.join_remote({ ["local"] = "", remote = "www" }, "a.txt"))
  end)
  it("handles an empty or root remote", function()
    assert.are.equal("a/b.txt", paths.join_remote({ ["local"] = "", remote = "" }, "a/b.txt"))
    assert.are.equal("/a/b.txt", paths.join_remote({ ["local"] = "", remote = "/" }, "a/b.txt"))
    assert.are.equal("/", paths.join_remote({ ["local"] = "", remote = "/" }, ""))
  end)
  it("mirrors trailing slashes", function()
    assert.are.equal("/var/www/app/", paths.join_remote({ ["local"] = "", remote = "/var/www/app" }, ""))
    assert.are.equal("/var/www/app/src/", paths.join_remote({ ["local"] = "", remote = "/var/www/app" }, "src/"))
    assert.are.equal("/var/www/app/src", paths.join_remote({ ["local"] = "", remote = "/var/www/app" }, "src"))
  end)
  it("returns nil when rel is outside the mapping", function()
    assert.is_nil(paths.join_remote({ ["local"] = "src", remote = "/r" }, "srcs/a"))
    assert.is_nil(paths.join_remote({ ["local"] = "src", remote = "/r" }, "other"))
  end)
end)
